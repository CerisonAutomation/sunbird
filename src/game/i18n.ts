let currentLang: Lang = "en";
let strings = STRINGS.en;

/** Detect browser language or load from save */
export function initLang(saved?: Lang): void {
  if (saved && STRINGS[saved]) {
    currentLang = saved;
  } else {
    const browser = navigator.language.slice(0, 2) as Lang;
    if (STRINGS[browser]) currentLang = browser;
  }
  strings = STRINGS[currentLang];
}

export function setLang(lang: Lang): void {
  if (!STRINGS[lang]) return;
  currentLang = lang;
  strings = STRINGS[lang];
}

export function getLang(): Lang {
  return currentLang;
}

/** Translate a key with optional {variable} interpolation */
export function t(key: string, vars?: Record<string, string | number>): string {
  let s = strings[key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return s;
}

/** Get all available translations for a key (for HUD snapshots) */
export function tAll(key: string): string {
  return strings[key] ?? STRINGS.en[key] ?? key;
}
